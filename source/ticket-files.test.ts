const valid = (config: Partial<PappardelleConfig>): ConfigLoad => ({
	kind: 'valid',
	config: {version: 1, profiles: {}, ...config},
});

test("a repo's PR rules come from its default profile, and its template from disk", () => {
	const checkout = tempDir('lasagna-repo-');
	expect(repoPrRules({kind: 'missing'} as ConfigLoad, checkout)).toEqual({});
	writeFiles(checkout, {'.github/PULL_REQUEST_TEMPLATE.md': '## What'});
	expect(repoPrRules(valid({}), checkout)).toEqual({
		prTemplate: '.github/PULL_REQUEST_TEMPLATE.md',
	});
	// What setup learned, or the user wrote, wins over what is found.
	expect(
		repoPrRules(
			valid({
				default_profile: 'b',
				profiles: {
					a: {display_name: 'A', vars: {PR_TITLE_FORMAT: 'no'}},
					b: {
						display_name: 'B',
						vars: {PR_TEMPLATE: 'docs/pr.md', PR_TITLE_FORMAT: '[KEY] Summary'},
						vcs: {label: 'b2b'},
					},
				},
			}),
			checkout,
		),
	).toEqual({
		prTemplate: 'docs/pr.md',
		prTitleFormat: '[KEY] Summary',
		prLabel: 'b2b',
	});
});

test("a file rule anchored at the repo gains the repo's directory; other rules are kept", () => {
	expect(rerootRule('Read(/src/**)', 'api')).toBe('Read(/api/src/**)');
	expect(rerootRule('Edit(./.env)', 'api')).toBe('Edit(./api/.env)');
	expect(rerootRule('Write(src/gen/**)', 'api')).toBe('Write(api/src/gen/**)');
	for (const rule of [
		'Read(//etc/hosts)',
		'Read(~/.ssh/**)',
		'Read(*.pem)',
		'Edit(**/secrets/**)',
		'Bash(yarn test:*)',
		'Bash(git -C ./src status)',
		'WebFetch(domain:example.com)',
		'mcp__jira__get_issue',
		'Read',
	])
		expect(rerootRule(rule, 'api')).toBe(rule);
});

test("the lead agent's settings are every repo's permissions, and no repo's hooks or env", () => {
	const merged = mergeRepoSettings([
		{
			name: 'tts-business',
			dir: 'tts-business',
			worktreePath: '/t/tts-business',
			settings: [
				{
					permissions: {
						allow: ['Bash(yarn lint)', 'Read(/docs/**)'],
						deny: ['Read(./.env)'],
						additionalDirectories: ['../shared'],
						defaultMode: 'acceptEdits',
					},
					hooks: {PreToolUse: [{hooks: [{type: 'command', command: 'x'}]}]},
					env: {SECRET: '1'},
					enabledPlugins: {
						'lasagna@lasagna-marketplace': true,
						'other@elsewhere': true,
					},
				},
				// The personal file, after the shared one.
				{permissions: {allow: ['Bash(yarn lint)', 'Bash(gh pr view:*)']}},
			],
		},
		{
			name: 'appian-server',
			dir: 'appian-server',
			worktreePath: '/t/appian-server',
			settings: [
				{
					permissions: {
						allow: ['Bash(./gradlew test:*)', 'Read(/docs/**)'],
						ask: ['Bash(git push:*)'],
						deny: 'not a list',
						defaultMode: 'acceptEdits',
					},
				},
				'not settings',
			],
		},
	]);
	expect(merged).toEqual({
		permissions: {
			allow: [
				'Bash(yarn lint)',
				'Read(/tts-business/docs/**)',
				'Bash(gh pr view:*)',
				'Bash(./gradlew test:*)',
				'Read(/appian-server/docs/**)',
			],
			deny: ['Read(./tts-business/.env)'],
			ask: ['Bash(git push:*)'],
			additionalDirectories: ['/t/shared'],
			// Every repo chose this mode.
			defaultMode: 'acceptEdits',
		},
		enabledPlugins: {'lasagna@lasagna-marketplace': true},
	});
	expect(JSON.stringify(merged)).not.toContain('hooks');
	expect(JSON.stringify(merged)).not.toContain('SECRET');
});

test('a mode is the ticket\u2019s only when every repo sets it, and repos with no settings merge to empty lists', () => {
	const repo = (name: string, ...modes: string[]) => ({
		name,
		dir: name,
		worktreePath: `/t/${name}`,
		settings: modes.map(defaultMode => ({permissions: {defaultMode}})),
	});
	const none = {permissions: {allow: [], deny: [], ask: []}};
	const disagree = [
		repo('api', 'acceptEdits'),
		repo('web', 'bypassPermissions'),
	];
	expect(mergeRepoSettings(disagree)).toEqual(none);
	expect(unsharedModes(disagree)).toEqual([
		{repo: 'api', mode: 'acceptEdits'},
		{repo: 'web', mode: 'bypassPermissions'},
	]);
	// One repo that skips every prompt does not make the others skip theirs.
	const one = [repo('api', 'bypassPermissions'), repo('web')];
	expect(mergeRepoSettings(one)).toEqual(none);
	expect(unsharedModes(one)).toEqual([
		{repo: 'api', mode: 'bypassPermissions'},
	]);
	// A repo's personal file has the last word on its own mode.
	const personal = [
		repo('api', 'default', 'acceptEdits'),
		repo('web', 'acceptEdits'),
	];
	expect(mergeRepoSettings(personal)).toEqual({
		permissions: {...none.permissions, defaultMode: 'acceptEdits'},
	});
	expect(unsharedModes(personal)).toEqual([]);
	expect(mergeRepoSettings([])).toEqual(none);
	expect(unsharedModes([repo('api'), repo('web')])).toEqual([]);
});

test("a repo's settings are read from its worktree: shared, then personal", () => {
	const ticket = tempDir('lasagna-ticket-');
	writeFiles(ticket, {
		'api/.claude/settings.json': '{"permissions": {"allow": ["Bash(a)"]}}',
		'api/.claude/settings.local.json':
			'{"permissions": {"allow": ["Bash(b)"]}}',
		'web/.claude/settings.json': '{ not json',
	});
	expect(
		readRepoSettings(ticket, {
			name: 'api',
			worktreePath: path.join(ticket, 'api'),
		}),
	).toEqual({
		name: 'api',
		dir: 'api',
		worktreePath: path.join(ticket, 'api'),
		settings: [
			{permissions: {allow: ['Bash(a)']}},
			{permissions: {allow: ['Bash(b)']}},
		],
	});
	expect(
		readRepoSettings(ticket, {
			name: 'web',
			worktreePath: path.join(ticket, 'web'),
		}).settings,
	).toEqual([]);
	// A worktree outside the folder goes by its repo's name.
	expect(
		readRepoSettings(ticket, {name: 'far', worktreePath: '/far/KEY'}).dir,
	).toBe('far');
});

test('closing removes what was generated and leaves everything else in the folder', () => {
	const ticket = tempDir('lasagna-ticket-');
	writeFiles(ticket, {
		'api/README.md': 'a worktree',
		'notes.md': 'the agent wrote this',
		'HANDOFF.md': 'generated',
	});
	writeTicketFiles(ticket, {claudeMd: '# T\n', settings: {permissions: {}}});
	expect(fs.readFileSync(path.join(ticket, 'CLAUDE.md'), 'utf8')).toBe('# T\n');
	expect(
		JSON.parse(
			fs.readFileSync(path.join(ticket, '.claude/settings.json'), 'utf8'),
		),
	).toEqual({permissions: {}});

	removeTicketFiles(ticket);
	expect(fs.readdirSync(ticket).sort()).toEqual(['api', 'notes.md']);

	// The user's own settings beside the generated ones stay, with their folder.
	writeTicketFiles(ticket, {claudeMd: '# T\n', settings: {}});
	writeFiles(ticket, {'.claude/settings.local.json': '{}'});
	removeTicketFiles(ticket);
	expect(fs.readdirSync(path.join(ticket, '.claude'))).toEqual([
		'settings.local.json',
	]);
	// Removing twice is fine.
	removeTicketFiles(ticket);
});
